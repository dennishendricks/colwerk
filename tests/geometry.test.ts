// WKB → WKT; the WKB values were produced by DuckDB (`hex(geom::blob)`), the EWKB values by PostGIS.
import { test } from 'bun:test'
import { assertEquals } from './assert.ts'
import { hexEwkbToText, mysqlGeometryToText, wkbToText } from '../core/geometry.ts'

const bytes = (hex: string) => Uint8Array.from(hex.match(/../g)!, (h) => Number.parseInt(h, 16))

test('geometry: ISO WKB as WKT', () => {
  const cases: [string, string][] = [
    ['0101000000000000000000F8BF9A9999999999B93F', 'POINT (-1.5 0.1)'],
    ['01E9030000000000000000F03F00000000000000400000000000000840', 'POINT Z (1 2 3)'],
    ['01D1070000000000000000F03F00000000000000400000000000001040', 'POINT M (1 2 4)'],
    ['01B90B0000000000000000F03F000000000000004000000000000008400000000000001040', 'POINT ZM (1 2 3 4)'],
    ['0101000000000000000000F87F000000000000F87F', 'POINT EMPTY'],
    ['010200000000000000', 'LINESTRING EMPTY'],
    [
      '0103000000010000000400000000000000000000000000000000000000000000000000F03F0000000000000000000000000000F03F000000000000F03F00000000000000000000000000000000',
      'POLYGON ((0 0, 1 0, 1 1, 0 0))',
    ],
    [
      '0104000000020000000101000000000000000000F03F0000000000000040010100000000000000000008400000000000001040',
      'MULTIPOINT ((1 2), (3 4))',
    ],
    [
      '010500000002000000010200000002000000000000000000F03F000000000000004000000000000008400000000000001040010200000002000000000000000000144000000000000018400000000000001C400000000000002040',
      'MULTILINESTRING ((1 2, 3 4), (5 6, 7 8))',
    ],
    [
      '0106000000020000000103000000010000000400000000000000000000000000000000000000000000000000F03F0000000000000000000000000000F03F000000000000F03F00000000000000000000000000000000010300000000000000',
      'MULTIPOLYGON (((0 0, 1 0, 1 1, 0 0)), EMPTY)',
    ],
    [
      '0107000000020000000101000000000000000000F03F0000000000000040010200000002000000000000000000F03F000000000000004000000000000008400000000000001040',
      'GEOMETRYCOLLECTION (POINT (1 2), LINESTRING (1 2, 3 4))',
    ],
    // Big-endian
    ['00000000013FF00000000000004000000000000000', 'POINT (1 2)'],
  ]
  for (const [hex, wkt] of cases) assertEquals(wkbToText(bytes(hex)), wkt)
})

test('geometry: unsupported or malformed values stay hex', () => {
  // CIRCULARSTRING EMPTY
  assertEquals(wkbToText(bytes('010800000000000000')), '0x010800000000000000')
  assertEquals(wkbToText(bytes('0101000000')), '0x0101000000')
})

test('geometry: PostGIS EWKB and MySQL keep the SRID', () => {
  assertEquals(hexEwkbToText('0101000020E6100000000000000000F03F0000000000000040'), 'SRID=4326;POINT (1 2)')
  assertEquals(
    hexEwkbToText('01010000A0E6100000000000000000F03F00000000000000400000000000000840'),
    'SRID=4326;POINT Z (1 2 3)',
  )
  assertEquals(
    mysqlGeometryToText(bytes('E61000000101000000000000000000F03F0000000000000040')),
    'SRID=4326;POINT (1 2)',
  )
  assertEquals(mysqlGeometryToText(bytes('000000000101000000000000000000F03F0000000000000040')), 'POINT (1 2)')
})
