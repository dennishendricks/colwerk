// File indexes for coding agents: writes core/CLAUDE.md, server/CLAUDE.md and app/CLAUDE.md with one line per
// source file, taken from its header comment, else its exports (API routes: method and path). Claude Code loads
// such a file when it reads files in that directory, so agents need not list and open files to find their way.
// `--check` only compares and exits with 1 if an index is outdated (CI). The pre-commit hook runs it.
import { readFile, writeFile } from 'node:fs/promises'

const DIRS = ['core', 'server', 'app']
/** Files from this size on get a hint to grep first and read in parts. */
const LARGE = 20_000
const MAX_EXPORTS = 10

const check = process.argv.includes('--check')

/** The first sentence of the `//` or `<!-- -->` comment the file starts with. */
function headerComment(text: string): string | undefined {
  const start = text.trimStart()
  let comment = ''
  if (start.startsWith('<!--')) comment = start.slice(4, start.indexOf('-->'))
  else
    for (const line of start.split('\n')) {
      if (!line.startsWith('//')) break
      comment += ` ${line.slice(2)}`
    }
  const sentence = comment
    .replace(/\s+/g, ' ')
    .trim()
    .split(/(?<=\.)\s+(?=[A-Z`])/)[0]
  return sentence?.replace(/\.$/, '') || undefined
}

function exportsOf(text: string): string | undefined {
  const names = [
    ...text.matchAll(
      /^export (?:default )?(?:declare )?(?:async )?(?:function\*?|const|let|class|interface|type|enum)\s+([\w$]+)/gm,
    ),
  ].map((m) => m[1])
  const modules = [...text.matchAll(/^export (?:\*|\{[^}]*\}) from '([^']+)'/gm)].map((m) => m[1])
  if (!names.length && modules.length) return `re-exports ${modules.join(', ')}`
  if (!names.length) return undefined
  const more = names.length > MAX_EXPORTS ? `, +${names.length - MAX_EXPORTS} more` : ''
  return `exports ${names.slice(0, MAX_EXPORTS).join(', ')}${more}`
}

/** `server/api/tabs/[id]/execute.post.ts` → `POST /api/tabs/:id/execute`. */
function route(path: string): string | undefined {
  const m = path.match(/^server\/api\/(.+?)(?:\.(get|post|put|patch|delete))?\.ts$/)
  if (!m) return undefined
  const url = `/api/${m[1]}`.replace(/\/index$/, '').replace(/\[(\w+)\]/g, ':$1')
  return `${(m[2] ?? 'ANY').toUpperCase()} ${url}`
}

async function index(dir: string): Promise<string> {
  const paths = (await Array.fromAsync(new Bun.Glob(`${dir}/**/*.{ts,vue}`).scan('.'))).sort()
  const lines = await Promise.all(
    paths.map(async (path) => {
      const text = await readFile(path, 'utf8')
      const parts = [route(path), headerComment(text) ?? (path.endsWith('.ts') ? exportsOf(text) : undefined)]
      if (text.length >= LARGE) parts.push(`**${Math.round(text.length / 1000)} KB: grep, then read in parts**`)
      const info = parts.filter(Boolean).join('; ')
      return `- \`${path.slice(dir.length + 1)}\`${info ? `: ${info}` : ''}`
    }),
  )
  return `<!-- Generated by scripts/agent-docs.ts from header comments and exports; do not edit. -->

# ${dir}/ file index

${lines.join('\n')}
`
}

let outdated = 0
for (const dir of DIRS) {
  const file = `${dir}/CLAUDE.md`
  const content = await index(dir)
  const current = await readFile(file, 'utf8').catch(() => '')
  if (content === current) continue
  if (check) {
    console.error(`${file} is outdated: run \`bun run agent-docs\``)
    outdated++
  } else await writeFile(file, content)
}
process.exit(outdated ? 1 : 0)
