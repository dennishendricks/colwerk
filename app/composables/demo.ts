// Demo data of the guided tours: a DuckDB database in memory, saved as connection "Colwerk Demo" on first use
import type { QueryTab } from './tabs'

const DEMO_NAME = 'Colwerk Demo'

/** Generated on the fly, so the in-memory database needs no tables (and loses nothing on restart). */
export const DEMO_SQL = `-- Demo data generated by DuckDB in memory
select
    i as order_id,
    date '2026-01-01' + (i * 7 % 300)::int as ordered_on,
    ['Berlin', 'Hamburg', 'Munich', 'Cologne', 'Leipzig'][i % 5 + 1] as city,
    ['Keyboard', 'Monitor', 'Mouse', 'Laptop'][i % 4 + 1] as product,
    (i * 37 % 9) + 1 as quantity,
    round((i * 7919 % 100000) / 100.0, 2) as amount
from range(1, 201) t(i);
`

export function useDemo() {
  const { connections, activeConnectionId, saveConnection } = useConnections()
  const { addTab } = useTabs()
  const { run } = useExecution()
  const { t } = useI18n()

  /** A new tab on the demo connection with `DEMO_SQL`, run when `execute` is set. */
  async function openTab(execute = false): Promise<QueryTab> {
    const existing = connections.value.find(
      (c) => c.dialect === 'duckdb' && c.file === ':memory:' && c.name === DEMO_NAME,
    )
    const id = existing?.id ?? (await saveConnection({ name: DEMO_NAME, dialect: 'duckdb', file: ':memory:' })).id
    activeConnectionId.value = id
    const tab = addTab(id)
    tab.title = t('tours.demoTab')
    tab.sql = DEMO_SQL
    if (execute) await run(tab, tab.sql)
    return tab
  }

  return { openTab, run }
}
